// Builds player/bridge.generated.ts: the frame shim with electron/preload.js
// inlined, and the wrapper page with electron/playerProtocol.js inlined, so
// the phone app runs the desktop player bridge unchanged. Run by `npm run
// bridge` (and before every start/build).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const mobile = join(here, '..');
const electron = join(mobile, '..', 'electron');

const preload = readFileSync(join(electron, 'preload.js'), 'utf8');
const protocol = readFileSync(join(electron, 'playerProtocol.js'), 'utf8');
const shim = readFileSync(join(mobile, 'player', 'shim.js'), 'utf8');
const wrapper = readFileSync(join(mobile, 'player', 'wrapper.html'), 'utf8');

// Function replacers: the inlined sources contain `$` sequences.
const shimOut = shim.replace('/*__PRELOAD__*/', () => preload);
const wrapperOut = wrapper.replace('/*__PLAYER_PROTOCOL__*/', () => protocol);

const out = `// Generated by scripts/build-bridge.mjs from player/shim.js,
// player/wrapper.html and electron/{preload,playerProtocol}.js. Don't edit.
export const SHIM_SOURCE = ${JSON.stringify(shimOut)};
export const WRAPPER_HTML = ${JSON.stringify(wrapperOut)};
`;
writeFileSync(join(mobile, 'player', 'bridge.generated.ts'), out);
console.log('player/bridge.generated.ts written');
